// ตั้งค่าและอ่านผลจาก Web Speech API (ตัวแปลงเสียงเป็นข้อความของเบราว์เซอร์)
//
// เคยมีชั้น "ช่วยเดาคำ" อยู่ตรงนี้ คือขอคำที่เป็นไปได้ 5 แบบจากเบราว์เซอร์
// แล้วเลือกแบบที่มีศัพท์ฟาร์ม (หมู/อุณหภูมิ/วัคซีน) มากที่สุด
// แต่แบบที่ 2-5 คือตัวเลือกที่เบราว์เซอร์มั่นใจน้อยกว่าอันดับ 1 อยู่แล้ว
// พอบังเอิญมีศัพท์ฟาร์มโผล่มา มันเลยทิ้งคำที่ถอดถูกไปเลือกคำที่ผิดแทน
// ผลคือยิ่งพูดยิ่งเพี้ยน จึงตัดออก แล้วเชื่ออันดับ 1 ของเบราว์เซอร์อย่างเดียว

// ประกอบข้อความเต็มจาก "ทุกท่อน" ที่พูดมา ไม่ใช่แค่ท่อนล่าสุด
// เวลาพูดประโยคยาวแล้วมีจังหวะเว้นวรรค เบราว์เซอร์จะตัดเป็นหลายท่อน (results[0], results[1], ...)
// ถ้าอ่านแค่ท่อนสุดท้ายจะได้ข้อความไม่ครบประโยค ต้องต่อทุกท่อนเข้าด้วยกันตามลำดับเสมอ
export function pickBestTranscript(results) {
  let text = ''
  for (let i = 0; i < results.length; i++) {
    text += results[i][0].transcript
  }
  return text
}

// ตั้งค่า SpeechRecognition ให้เหมาะกับการฟังภาษาไทยเรื่องสภาพอากาศ/ฟาร์ม
// continuous -> ฟังต่อเนื่องข้ามจังหวะเว้นวรรคในประโยคเดียวกัน ไม่ตัดกลางประโยคตอนหยุดหายใจสั้น ๆ
// interimResults -> เห็นข้อความไหลมาระหว่างพูด จะได้รู้ว่าระบบได้ยินถูกไหมก่อนส่ง
export function createRecognizer() {
  const SR = window.SpeechRecognition || window.webkitSpeechRecognition
  if (!SR) return null
  const r = new SR()
  r.lang = 'th-TH'
  r.interimResults = true
  r.maxAlternatives = 1
  r.continuous = true
  return r
}
